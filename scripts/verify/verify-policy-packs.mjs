#!/usr/bin/env node
/**
 * Validates i18n-packs/policy-packs/v1.json schema and sync with embedded policyPackData.
 */
import fs from 'node:fs';
import path from 'node:path';
import { canonicalPolicyPackPath, I18N_PACKS_DIR } from '../../packages/shared/src/i18n/packPaths.mjs';

const root = process.cwd();
const packPath = canonicalPolicyPackPath(root);
let failed = false;

function fail(msg) {
  console.error(`verify-policy-packs: ${msg}`);
  failed = true;
}

if (!fs.existsSync(packPath)) {
  fail('missing i18n-packs/policy-packs/v1.json');
  process.exit(1);
}

const pack = JSON.parse(fs.readFileSync(packPath, 'utf8'));
const requiredRegions = ['eea_uk', 'us_ca', 'us_other', 'au', 'br', 'other'];

if (!pack.version && !pack.policyPackId) fail('missing version or policyPackId');
if (!pack.regions || typeof pack.regions !== 'object') fail('missing regions object');

for (const id of requiredRegions) {
  const r = pack.regions[id];
  if (!r) fail(`missing region ${id}`);
  else {
    if (!r.label) fail(`${id} missing label`);
    if (!Array.isArray(r.policyDocuments) || r.policyDocuments.length === 0) fail(`${id} missing policyDocuments`);
    if (!r.features || typeof r.features !== 'object') fail(`${id} missing features`);
    if (!r.requiredDataResidency) fail(`${id} missing requiredDataResidency`);
    if (!r.defaultLocale) fail(`${id} missing defaultLocale`);
  }
}

const embeddedPath = path.join(root, 'packages', 'shared', I18N_PACKS_DIR, 'policy-packs', 'v1.json');
if (!fs.existsSync(embeddedPath)) {
  fail(`missing packages/shared/${I18N_PACKS_DIR}/policy-packs/v1.json — run node scripts/i18n/sync-policy-pack.mjs`);
} else {
  const canonical = fs.readFileSync(packPath, 'utf8');
  const embedded = fs.readFileSync(embeddedPath, 'utf8');
  if (canonical !== embedded) {
    fail(`packages/shared/${I18N_PACKS_DIR}/policy-packs/v1.json out of sync with i18n-packs/policy-packs/v1.json`);
  }
}

const embeddedSrcPath = path.join(root, 'packages', 'shared', 'src', 'privacy', 'policyPackData.mjs');
if (!fs.existsSync(embeddedSrcPath)) {
  fail('missing policyPackData.mjs — run node scripts/i18n/sync-policy-pack.mjs');
} else {
  const src = fs.readFileSync(embeddedSrcPath, 'utf8');
  if (!src.includes('Generated by scripts/i18n/sync-policy-pack.mjs')) {
    fail('policyPackData.mjs must be generated by scripts/i18n/sync-policy-pack.mjs');
  }
  const mod = await import(pathToFileUrl(embeddedSrcPath));
  if (JSON.stringify(mod.POLICY_PACK_V1) !== JSON.stringify(pack)) {
    fail('policyPackData.mjs POLICY_PACK_V1 out of sync with i18n-packs/policy-packs/v1.json');
  }
}

if (failed) process.exit(1);
console.log('verify-policy-packs: i18n-packs/policy-packs/v1.json valid');

function pathToFileUrl(filePath) {
  const resolved = path.resolve(filePath);
  return new URL(`file:///${resolved.replace(/\\/g, '/')}`).href;
}
