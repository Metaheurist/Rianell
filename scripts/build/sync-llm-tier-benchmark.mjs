#!/usr/bin/env node
/**
 * Emit apps/pwa-webapp/llm-tier-benchmark-sync.js for IIFE scripts (device-benchmark.js).
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { msPer200kToTier, tierToLlmModelSize } from '../../packages/llm/src/tier-benchmark.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const out = join(root, 'apps', 'pwa-webapp', 'llm-tier-benchmark-sync.js');

const body = `// AUTO-GENERATED by scripts/build/sync-llm-tier-benchmark.mjs — do not edit.
(function (global) {
  'use strict';
  function msPer200kToTier(msPer200k) {
    if (msPer200k <= 8.0) return 5;
    if (msPer200k <= 12.0) return 4;
    if (msPer200k <= 18.0) return 3;
    if (msPer200k <= 26.0) return 2;
    return 1;
  }
  function tierToLlmModelSize(tier) {
    var n = typeof tier === 'number' ? tier : Number(String(tier).replace('tier', ''));
    if (n >= 5) return 'tier5';
    if (n === 4) return 'tier4';
    if (n === 3) return 'tier3';
    if (n === 2) return 'tier2';
    return 'tier1';
  }
  global.RianellLlmTierBenchmark = {
    msPer200kToTier: msPer200kToTier,
    tierToLlmModelSize: tierToLlmModelSize,
    version: 1
  };
})(typeof window !== 'undefined' ? window : globalThis);
`;

// Verify source matches before write
if (msPer200kToTier(7) !== 5 || tierToLlmModelSize(3) !== 'tier3') {
  throw new Error('tier-benchmark sanity check failed');
}

writeFileSync(out, body, 'utf8');
console.log('Wrote', out);
