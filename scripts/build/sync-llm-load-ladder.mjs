#!/usr/bin/env node
/**
 * Emit apps/pwa-webapp/llm-load-ladder-sync.js for summary-llm.js (IIFE).
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { buildPwaLoadAttempts, buildPwaWasmAttempt } from '../../packages/llm/src/load-ladder.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const out = join(root, 'apps', 'pwa-webapp', 'llm-load-ladder-sync.js');

if (buildPwaLoadAttempts({ platformKind: 'pwa_desktop', gpuCandidates: ['webgpu'] }).length < 2) {
  throw new Error('load-ladder sanity check failed');
}

const body = `// AUTO-GENERATED by scripts/build/sync-llm-load-ladder.mjs — do not edit.
(function (global) {
  'use strict';
  var MAX_PWA_ATTEMPTS = 8;

  function buildPwaLoadAttempts(options) {
    options = options || {};
    var platformKind = options.platformKind || 'pwa_desktop';
    var gpuCandidates = options.gpuCandidates || [];
    var plans = [];
    var seen = Object.create(null);
    function add(device, dtype) {
      var key = device + ':' + dtype;
      if (seen[key] || plans.length >= MAX_PWA_ATTEMPTS) return;
      seen[key] = true;
      plans.push({ device: device, dtype: dtype, revision: 'main' });
    }
    for (var i = 0; i < gpuCandidates.length; i++) {
      var device = gpuCandidates[i];
      if (device === 'webgpu') {
        add('webgpu', 'q4f16');
        add('webgpu', 'q4');
      }
    }
    return plans;
  }

  function buildPwaWasmAttempt() {
    return { revision: 'main', device: 'wasm', dtype: 'q4' };
  }

  function resolvePlatformKindFromWindow() {
    if (typeof window !== 'undefined' && window.DeviceBenchmark) {
      if (typeof window.DeviceBenchmark.getPlatformTypeCached === 'function') {
        var pt = window.DeviceBenchmark.getPlatformTypeCached();
        return pt === 'mobile' ? 'pwa_mobile' : 'pwa_desktop';
      }
      if (typeof window.DeviceBenchmark.getPlatformType === 'function') {
        return window.DeviceBenchmark.getPlatformType() === 'mobile' ? 'pwa_mobile' : 'pwa_desktop';
      }
    }
    return 'pwa_desktop';
  }

  global.RianellLlmLoadLadder = {
    buildPwaLoadAttempts: buildPwaLoadAttempts,
    buildPwaWasmAttempt: buildPwaWasmAttempt,
    resolvePlatformKindFromWindow: resolvePlatformKindFromWindow,
    version: 2
  };
})(typeof window !== 'undefined' ? window : globalThis);
`;

writeFileSync(out, body, 'utf8');
console.log('Wrote', out);

// eslint-disable-next-line no-unused-vars
const _wasm = buildPwaWasmAttempt();
