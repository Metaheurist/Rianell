#!/usr/bin/env node
/**
 * Emit apps/pwa-webapp/llm-runtime-profiles-sync.js for summary-llm.js (IIFE).
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { resolveWasmOnlyCap, parseOomError, LAST_STABLE_PRESET_KEY } from '../../packages/llm/src/runtime-profiles.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const out = join(root, 'apps', 'pwa-webapp', 'llm-runtime-profiles-sync.js');

if (resolveWasmOnlyCap({ tier: 'tier5', webGpuAvailable: false }).tier !== 'tier2') {
  throw new Error('runtime-profiles sanity check failed');
}

const body = `// AUTO-GENERATED by scripts/build/sync-llm-runtime-profiles.mjs — do not edit.
(function (global) {
  'use strict';

  function tierToLlmModelSize(tier) {
    var n = typeof tier === 'number' ? tier : Number(String(tier).replace('tier', ''));
    if (n >= 5) return 'tier5';
    if (n === 4) return 'tier4';
    if (n === 3) return 'tier3';
    if (n === 2) return 'tier2';
    return 'tier1';
  }

  function resolveWasmOnlyCap(options) {
    options = options || {};
    var tier = options.tier || 'tier3';
    var webGpuAvailable = !!options.webGpuAvailable;
    var forceLargeOnWasm = !!options.forceLargeOnWasm;
    var deviceMemory = options.deviceMemory != null ? options.deviceMemory : null;
    var tierKey = /^tier[1-5]$/.test(tier) ? tier : tierToLlmModelSize(tier);

    if (webGpuAvailable) {
      return { tier: tierKey, capped: false, warning: null };
    }
    if (tierKey === 'tier1' || tierKey === 'tier2') {
      return { tier: tierKey, capped: false, warning: null };
    }
    if (forceLargeOnWasm && deviceMemory != null && deviceMemory >= 8) {
      return {
        tier: tierKey,
        capped: false,
        warning: 'Large model on WASM-only - may be slow or run out of memory.'
      };
    }
    return {
      tier: 'tier2',
      capped: true,
      warning: 'No GPU acceleration available; using smaller AI model for stability.'
    };
  }

  function parseOomError(err) {
    var msg = String(err && err.message ? err.message : err || '').toLowerCase();
    return /out of memory|oom|memory allocation|failed to allocate|array buffer allocation/i.test(msg);
  }

  global.RianellLlmRuntimeProfiles = {
    resolveWasmOnlyCap: resolveWasmOnlyCap,
    parseOomError: parseOomError,
    LAST_STABLE_PRESET_KEY: ${JSON.stringify(LAST_STABLE_PRESET_KEY)},
    version: 1
  };
})(typeof window !== 'undefined' ? window : globalThis);
`;

writeFileSync(out, body, 'utf8');
console.log('Wrote', out);
