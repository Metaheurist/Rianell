#!/usr/bin/env node
/**
 * Regenerates docs/security-inventory.md — npm/pip deps, CDN loads, SRI matrix, storage keys, Supabase tables.
 * Usage: node scripts/generate-security-inventory.mjs [--check]
 */
import fs from 'fs';
import path from 'path';

const SCHEMA_VERSION = 1;
const root = process.cwd();
const outPath = path.join(root, 'docs', 'security-inventory.md');

function readText(rel) {
  return fs.readFileSync(path.join(root, rel), 'utf8');
}

function readJson(rel) {
  return JSON.parse(readText(rel));
}

function extractCdnUrls(html) {
  const urls = [];
  const re = /<script[^>]+src=["']([^"']+)["']/gi;
  let m;
  while ((m = re.exec(html))) urls.push(m[1]);
  const linkRe = /<link[^>]+href=["']([^"']+)["']/gi;
  while ((m = linkRe.exec(html))) urls.push(m[1]);
  return [...new Set(urls.filter((u) => /^https?:\/\//.test(u)))];
}

function extractStorageKeys(source, pattern) {
  const keys = new Set();
  let m;
  const re = pattern;
  while ((m = re.exec(source))) keys.add(m[1]);
  return [...keys].sort();
}

function generate() {
  const rootPkg = readJson('package.json');
  const rnPkg = readJson('apps/rn-app/package.json');
  const indexHtml = readText('apps/pwa-webapp/index.html');
  const schemaSql = readText('supabase/Schema.sql');
  const appJs = readText('apps/pwa-webapp/app.js');
  const cloudSync = readText('apps/pwa-webapp/cloud-sync.js');

  const cdnUrls = extractCdnUrls(indexHtml);
  const sriLines = (indexHtml.match(/integrity="[^"]+"/g) || []).length;

  const localStorageKeys = extractStorageKeys(
    appJs + cloudSync,
    /localStorage\.(?:getItem|setItem|removeItem)\(['"]([^'"]+)['"]/g
  );

  const tables = [...schemaSql.matchAll(/CREATE TABLE public\.(\w+)/g)].map((m) => m[1]);

  const lines = [
    '<!-- generated by scripts/generate-security-inventory.mjs; do not edit -->',
    '',
    `# Security inventory`,
    '',
    `Schema version: **${SCHEMA_VERSION}** · Generated for Rianell security program.`,
    '',
    '## npm workspaces',
    '',
    `| Package | Version |`,
    `|---------|---------|`,
    `| \`rianell\` (root) | ${rootPkg.version} |`,
    `| \`apps/rn-app\` | ${rnPkg.version} |`,
    '',
    '## Python',
    '',
    'See `requirements.txt` (scanned by pip-audit in CI).',
    '',
    '## PWA CDN URLs (index.html)',
    '',
    ...cdnUrls.map((u) => `- ${u}`),
    '',
    `SRI integrity attributes in index.html: **${sriLines}** (expand via \`apps/pwa-webapp/cdn-manifest.json\`).`,
    '',
    '## Sensitive localStorage keys (sample)',
    '',
    ...localStorageKeys.slice(0, 40).map((k) => `- \`${k}\``),
    localStorageKeys.length > 40 ? `- … and ${localStorageKeys.length - 40} more` : '',
    '',
    '## Supabase tables',
    '',
    ...tables.map((t) => `- \`public.${t}\``),
    '',
    '## Subprocessors',
    '',
    'See [docs/privacy/subprocessors.md](privacy/subprocessors.md).',
    '',
  ];

  return `${lines.filter(Boolean).join('\n')}\n`;
}

const content = generate();

if (process.argv.includes('--check')) {
  if (!fs.existsSync(outPath)) {
    console.error('security-inventory: missing', outPath);
    process.exit(1);
  }
  const existing = fs.readFileSync(outPath, 'utf8');
  if (existing !== content) {
    console.error('security-inventory: docs/security-inventory.md is out of date. Run: node scripts/generate-security-inventory.mjs');
    process.exit(1);
  }
  console.log('security-inventory: OK');
} else {
  fs.writeFileSync(outPath, content);
  console.log('Wrote', outPath);
}
