#!/usr/bin/env node
/**
 * Materialize completed visual-gen outputs into a runtime override module:
 *   apps/pwa-webapp/modules/visual-overrides.generated.js
 *
 * graphics-portfolio / FA mappers can consult window.__RIANELL_VISUAL_OVERRIDES.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '../..');
const registerPath = path.join(root, 'apps/pwa-webapp/assets/visual-register.json');
const checkpointPath = path.join(root, 'artifacts/visual-gen/checkpoint.json');
const outPath = path.join(root, 'apps/pwa-webapp/modules/visual-overrides.generated.js');

function load(p, fb) {
  if (!fs.existsSync(p)) return fb;
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

const register = load(registerPath, { entries: [] });
const cp = load(checkpointPath, { completed: {} });
const map = {};

for (const entry of register.entries || []) {
  if (!cp.completed?.[entry.id] && entry.genStatus !== 'done') continue;
  const polishedRel = String(entry.outputPath || '').replace(/^artifacts\/visual-gen\//, 'artifacts/visual-gen/polished/');
  const polishedAbs = path.join(root, polishedRel);
  const abs = fs.existsSync(polishedAbs) ? polishedAbs : path.join(root, entry.outputPath);
  if (!fs.existsSync(abs)) continue;
  let text = fs.readFileSync(abs, 'utf8').trim();
  text = text.replace(/^```(?:svg|xml|css|js)?\s*/i, '').replace(/\s*```$/i, '').trim();
  if (!text) continue;
  map[entry.id] = {
    kind: entry.kind,
    viewBox: entry.viewBox || '',
    markup: text,
  };
}

const body = `/* AUTO-GENERATED by scripts/dev/visual-gen-write-overrides.mjs — do not edit */
(function (global) {
  'use strict';
  var OVERRIDES = ${JSON.stringify(map, null, 2)};
  global.__RIANELL_VISUAL_OVERRIDES = OVERRIDES;
  global.RianellVisualOverrides = {
    get: function (id) { return OVERRIDES[id] || null; },
    keys: function () { return Object.keys(OVERRIDES); },
    size: Object.keys(OVERRIDES).length
  };
})(typeof window !== 'undefined' ? window : globalThis);
`;

fs.writeFileSync(outPath, body);
console.log(`[visual-overrides] wrote ${outPath} entries=${Object.keys(map).length}`);
