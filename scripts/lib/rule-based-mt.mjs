function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

export function applyRuleBasedMt(text, locale) {
  const map = PHRASES[locale];
  if (!map || typeof text !== 'string') return text;
  let out = text;
  const entries = Object.entries(map).sort((a, b) => b[0].length - a[0].length);
  for (const [en, loc] of entries) {
    out = out.replace(new RegExp(`\\b${escapeRe(en)}\\b`, 'gi'), (m) => {
      if (m === m.toUpperCase()) return loc.toUpperCase();
      if (m[0] === m[0].toUpperCase()) return loc.charAt(0).toUpperCase() + loc.slice(1);
      return loc;
    });
  }
  return out;
}

export function shouldKeepEnglish(text) {
  if (!text || typeof text !== 'string') return true;
  const t = text.trim();
  if (!t) return true;
  if (GLOSSARY_TERMS.some((g) => t.includes(g))) return true;
  if (/^(OK|No|Yes|Beta|Cardio|cal|kg|ml)$/i.test(t)) return true;
  if (/\$\{|escapeAttr|\.label\s*\|\||YYYY-MM-DD/.test(t)) return true;
  if (/^\{[a-zA-Z]+\}$/.test(t)) return true;
  return false;
}
