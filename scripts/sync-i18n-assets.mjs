#!/usr/bin/env node
/**
 * Sync i18n-packs (locale, prompt, motd, policy) to PWA/RN/shared targets.
 */
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import {
  canonicalLocalePacksDir,
  canonicalMotdPacksDir,
  canonicalPromptPacksDir,
  I18N_PACKS_DIR,
} from '../packages/shared/src/i18n/packPaths.mjs';

const root = process.cwd();

function copyJsonDir(srcAbs, destRels) {
  if (!fs.existsSync(srcAbs)) {
    console.error(`sync-i18n-assets: missing ${path.relative(root, srcAbs)}`);
    process.exit(1);
  }
  for (const destRel of destRels) {
    const dest = path.join(root, destRel);
    fs.mkdirSync(dest, { recursive: true });
    for (const name of fs.readdirSync(srcAbs)) {
      if (name.endsWith('.json')) {
        fs.copyFileSync(path.join(srcAbs, name), path.join(dest, name));
      }
    }
  }
}

const localeSrc = canonicalLocalePacksDir(root);
const promptSrc = canonicalPromptPacksDir(root);
const motdSrc = canonicalMotdPacksDir(root);

copyJsonDir(localeSrc, [
  `apps/pwa-webapp/${I18N_PACKS_DIR}/locale-packs/v1`,
  `apps/rn-app/${I18N_PACKS_DIR}/locale-packs/v1`,
]);

copyJsonDir(promptSrc, [
  `packages/shared/${I18N_PACKS_DIR}/prompt-packs/v1`,
  `apps/pwa-webapp/${I18N_PACKS_DIR}/prompt-packs/v1`,
  `apps/rn-app/${I18N_PACKS_DIR}/prompt-packs/v1`,
]);

copyJsonDir(motdSrc, [
  `packages/shared/${I18N_PACKS_DIR}/motd-packs/v1`,
  `apps/pwa-webapp/${I18N_PACKS_DIR}/motd-packs/v1`,
  `apps/rn-app/${I18N_PACKS_DIR}/motd-packs/v1`,
]);

function generatePromptPackData() {
  const outPath = path.join(root, 'packages', 'shared', 'src', 'i18n', 'promptPackData.mjs');
  const packs = {};
  for (const name of fs.readdirSync(promptSrc)) {
    if (!name.endsWith('.json')) continue;
    const localeId = name.replace(/\.json$/, '');
    packs[localeId] = JSON.parse(fs.readFileSync(path.join(promptSrc, name), 'utf8'));
  }
  const generated = `// Generated by scripts/sync-i18n-assets.mjs — do not edit manually.
export const PROMPT_PACKS_V1 = ${JSON.stringify(packs, null, 2)};
`;
  fs.writeFileSync(outPath, generated, 'utf8');
  console.log('sync-i18n-assets: regenerated packages/shared/src/i18n/promptPackData.mjs');
}

generatePromptPackData();

const policy = spawnSync(process.execPath, ['scripts/sync-policy-pack.mjs'], {
  cwd: root,
  stdio: 'inherit',
});
if (policy.status !== 0) process.exit(policy.status || 1);

console.log('sync-i18n-assets: locale, prompt, motd, and policy packs synced');
