#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { canonicalPolicyPackPath, I18N_PACKS_DIR } from '../packages/shared/src/i18n/packPaths.mjs';

const root = process.cwd();
const src = canonicalPolicyPackPath(root);
const destDir = path.join(root, 'packages', 'shared', I18N_PACKS_DIR, 'policy-packs');
const dest = path.join(destDir, 'v1.json');
const policyPackDataPath = path.join(
  root,
  'packages',
  'shared',
  'src',
  'privacy',
  'policyPackData.mjs'
);

if (!fs.existsSync(src)) {
  console.error(`sync-policy-pack: missing ${path.relative(root, src)}`);
  process.exit(1);
}

const raw = fs.readFileSync(src, 'utf8');
let pack;
try {
  pack = JSON.parse(raw);
} catch (err) {
  console.error(`sync-policy-pack: invalid JSON in ${path.relative(root, src)}`, err);
  process.exit(1);
}

fs.mkdirSync(destDir, { recursive: true });
fs.writeFileSync(dest, raw, 'utf8');

const generated = `// Generated by scripts/sync-policy-pack.mjs — do not edit manually.
export const POLICY_PACK_V1 = ${JSON.stringify(pack, null, 2)};
`;
fs.writeFileSync(policyPackDataPath, generated, 'utf8');

console.log(`sync-policy-pack: copied to packages/shared/${I18N_PACKS_DIR}/policy-packs/v1.json`);
console.log('sync-policy-pack: regenerated packages/shared/src/privacy/policyPackData.mjs');
