#!/usr/bin/env node
/**
 * Merge Tier C (ga / ar / he) locale pack strings that differ from en-GB into
 * scripts/lib/ollama-tier-c-overrides.mjs. Keeps generate-locale-overrides.mjs
 * reproducible without re-running the local translation model.
 */
import fs from 'node:fs';
import path from 'node:path';
import { canonicalLocalePacksDir } from '../../packages/shared/src/i18n/packPaths.mjs';
import { OLLAMA_TIER_C_OVERRIDES } from '../lib/ollama-tier-c-overrides.mjs';
import { shouldKeepEnglish } from '../lib/rule-based-mt.mjs';

const root = process.cwd();
const dir = canonicalLocalePacksDir(root);
const outPath = path.join(root, 'scripts/lib/ollama-tier-c-overrides.mjs');
const TIER_C = ['ga', 'ar', 'he'];

const canonical = JSON.parse(fs.readFileSync(path.join(dir, 'en-GB.json'), 'utf8'));
const en = canonical.strings || {};
const merged = structuredClone(OLLAMA_TIER_C_OVERRIDES);

for (const locale of TIER_C) {
  const filePath = path.join(dir, `${locale}.json`);
  if (!fs.existsSync(filePath)) {
    console.warn(`merge-tier-c-overrides: missing ${locale}.json — skipping`);
    continue;
  }
  const pack = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  const strings = pack.strings || {};
  if (!merged[locale]) merged[locale] = {};
  let added = 0;
  for (const [key, enVal] of Object.entries(en)) {
    if (key.startsWith('policy.')) continue;
    if (typeof enVal !== 'string') continue;
    if (shouldKeepEnglish(enVal)) continue;
    const locVal = strings[key];
    if (typeof locVal !== 'string' || locVal.trim() === enVal.trim()) continue;
    if (merged[locale][key] === locVal) continue;
    merged[locale][key] = locVal;
    added += 1;
  }
  console.log(`merge-tier-c-overrides: ${locale} +${added} (total ${Object.keys(merged[locale]).length})`);
}

function serialize(obj) {
  const lines = ['{'];
  for (const loc of TIER_C) {
    const map = obj[loc] || {};
    lines.push(`  '${loc}': {`);
    for (const [key, val] of Object.entries(map)) {
      lines.push(`    ${JSON.stringify(key)}: ${JSON.stringify(val)},`);
    }
    lines.push('  },');
  }
  lines.push('};');
  return lines.join('\n');
}

const header = `/**
 * Tier C (ga / ar / he) locale overrides produced by the local Ollama
 * TranslateGemma gap-fill (scripts/i18n/ollama-translate-gaps.mjs).
 *
 * Regenerated by scripts/i18n/merge-tier-c-overrides-from-packs.mjs so that
 * generate-locale-overrides.mjs can rebuild these packs from en-GB without
 * re-running the model. Keys hold locale strings that differ from en-GB.
 */
`;

fs.writeFileSync(outPath, `${header}export const OLLAMA_TIER_C_OVERRIDES = ${serialize(merged)}\n`, 'utf8');
console.log(`merge-tier-c-overrides: wrote ${outPath}`);
