#!/usr/bin/env node
/**
 * Generate scripts/lib/tier-a-exact-overrides.mjs from en-GB identical keys.
 * Uses DEEPL / Google / MyMemory when configured; falls back to rule-based MT.
 */
import fs from 'node:fs';
import path from 'node:path';
import { canonicalLocalePacksDir } from '../../packages/shared/src/i18n/packPaths.mjs';
import { translateText } from '../lib/machine-translate.mjs';
import { shouldKeepEnglish } from '../lib/rule-based-mt.mjs';

const root = process.cwd();
const dir = canonicalLocalePacksDir(root);
const TIER_A = ['pt-BR', 'fr-FR', 'de-DE', 'es-ES', 'it-IT', 'nl-NL', 'pl-PL', 'pt-PT'];
const delayMs = Number(process.env.MT_DELAY_MS || '200');
const outPath = path.join(root, 'scripts/lib/tier-a-exact-overrides.mjs');

const canonical = JSON.parse(fs.readFileSync(path.join(dir, 'en-GB.json'), 'utf8'));
const en = canonical.strings || {};

const EXACT_OVERRIDES = {};

for (const locale of TIER_A) {
  const pack = JSON.parse(fs.readFileSync(path.join(dir, `${locale}.json`), 'utf8'));
  const strings = pack.strings || {};
  const overrides = {};
  const keys = Object.keys(en).filter((k) => !k.startsWith('policy.'));

  for (let i = 0; i < keys.length; i++) {
    const key = keys[i];
    const enVal = en[key];
    if (typeof enVal !== 'string' || !enVal.trim()) continue;
    if (shouldKeepEnglish(enVal)) continue;
    const cur = strings[key];
    if (typeof cur !== 'string' || cur.trim() !== enVal.trim()) continue;

    try {
      const translated = await translateText(enVal, locale);
      if (translated && translated.trim() !== enVal.trim()) {
        overrides[key] = translated;
      }
    } catch (e) {
      console.warn(`generate: ${locale} ${key}: ${e.message}`);
    }

    if (delayMs > 0) await new Promise((r) => setTimeout(r, delayMs));
    if ((i + 1) % 25 === 0) {
      console.log(`generate: ${locale} ${i + 1}/${keys.length} (${Object.keys(overrides).length} overrides)`);
    }
  }

  EXACT_OVERRIDES[locale] = overrides;
  console.log(`generate: ${locale} done — ${Object.keys(overrides).length} override(s)`);
}

function serialize(obj, indent = 0) {
  const pad = '  '.repeat(indent);
  const padInner = '  '.repeat(indent + 1);
  const lines = ['{'];
  for (const [loc, map] of Object.entries(obj)) {
    lines.push(`${padInner}'${loc}': {`);
    for (const [key, val] of Object.entries(map)) {
      lines.push(`${padInner}  ${JSON.stringify(key)}: ${JSON.stringify(val)},`);
    }
    lines.push(`${padInner}},`);
  }
  lines.push(`${pad}}`);
  return lines.join('\n');
}

const header = `/**
 * Exact en-GB → locale overrides for Tier A packs (LC-16 offline completion).
 * Keys where locale strings still matched en-GB after rule-based MT.
 * Generated by scripts/i18n/generate-tier-a-exact-overrides.mjs — edit manually as needed.
 */
`;

fs.writeFileSync(outPath, `${header}export const EXACT_OVERRIDES = ${serialize(EXACT_OVERRIDES)};\n`, 'utf8');
console.log(`generate: wrote ${outPath}`);
